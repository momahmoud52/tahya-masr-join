const lastMsg = {};
/* يختار رسالة عشوائية مختلفة عن آخر رسالة ظهرت لنفس النتيجة */
const pickMessage = (decision, r) => {
  const list = RESULT_MESSAGES[decision];
  if (!list?.length) return "";
  let i;
  do i = Math.floor(Math.random() * list.length);
  while (list.length > 1 && i === lastMsg[decision]);
  lastMsg[decision] = i;
  return list[i]
    .replaceAll("{name}", esc(r.name_ar.trim().split(/\s+/)[0]))
    .replaceAll("{committee}", esc(r.committee));
};
